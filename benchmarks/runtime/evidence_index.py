"""
The Phase 1 evidence index (TEST-ONLY tooling): every batch under ``benchmarks/evidence/`` with
its plan title, the code commit(s) its parts ran, and its parts and rows. Writes
``docs/runtime/PHASE1_EVIDENCE_INDEX.md``.

usage: evidence_index.py [OUT.md]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EVIDENCE = ROOT / "benchmarks" / "evidence"
HEADER = """# Phase 1 evidence index (generated by `benchmarks/runtime/evidence_index.py`)

Every batch under `benchmarks/evidence/`: its plan (written before any row), the code commit(s)
its parts ran, and its parts and rows. Results and reasoning are in
`PHASE1_ENGINEERING_RECORD.md`. Every row is synthetic fault injection on named, pinned
servers, never production traffic.

| Suite | Batch | Plan title | Code | Parts | Rows |
|---|---|---|---|---|---|
"""


def main(argv: list[str]) -> int:
    out = Path(argv[0]) if argv else ROOT / "docs" / "runtime" / "PHASE1_EVIDENCE_INDEX.md"
    lines = []
    for plan in sorted(EVIDENCE.glob("*/*/PLAN.md")):
        batch = plan.parent
        title = plan.read_text().splitlines()[0].lstrip("# ").strip()
        commits = sorted(
            {json.loads(c.read_text()).get("commit", "")[:7] for c in batch.glob("codestate*.json")}
            - {""}
        )
        parts = sorted(batch.glob("rows*.jsonl"))
        rows = sum(sum(1 for line in p.open() if line.strip()) for p in parts)
        code = ", ".join(commits) or "-"
        lines.append(
            f"| {batch.parent.name} | {batch.name} | {title} | {code} | {len(parts)} | {rows} |"
        )
    out.write_text(HEADER + "\n".join(lines) + "\n")
    print(f"{len(lines)} batches -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
