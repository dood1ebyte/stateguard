"""
Property tests at the MCP boundary: invariants over generated drifted calls.

Calls are generated by mutating known-valid calls to the corpus tools the
way models drift -- a key re-cased, abbreviated, truncated or renamed, a
number stringified, an enum re-spelled, a key dropped or added, a value of
the wrong type, the whole object double-encoded. For every generated call,
in both modes:

* **determinism** -- the same call yields the same record;
* **shadow isolation** -- shadow forwards exactly what was received, and
  reports the same decision auto mode makes;
* **validity** -- anything auto mode forwards re-validates;
* **idempotence** -- feeding a forwarded payload back changes nothing;
* **provenance** -- every forwarded value was sent, moved by a recorded
  repair, or is a declared default;
* **ambiguity safety** -- a key held as ambiguous is never moved: if the
  call is forwarded, the key is still where the model put it.
"""

from __future__ import annotations

import copy
import json
from pathlib import Path
from typing import Any

from hypothesis import given, settings
from hypothesis import strategies as st

from stateguard import ContractGuard, GuardConfig
from stateguard.adapters.mcp import MCPAction, ToolRegistry
from stateguard.core.errors.operations import FieldOpType
from stateguard.core.explain import FieldDecisionKind
from stateguard.core.models.config import RepairMode

CORPUS = json.loads((Path(__file__).parent / "corpus" / "drift_corpus.json").read_text())

#: One known-valid call per tool, taken from the corpus's own forwards.
VALID: dict[str, dict[str, Any]] = {}
for _case in CORPUS["calls"]:
    if (
        _case["class"] in ("repairable", "unchanged")
        and _case.get("forward")
        and not _case.get("known_gap")
    ):
        VALID.setdefault(_case["tool"], _case["forward"])

AUTO = ToolRegistry()
AUTO.sync(CORPUS["tools"].values())
SHADOW = ToolRegistry(ContractGuard.with_mcp(config=GuardConfig(mode=RepairMode.SHADOW)))
SHADOW.sync(CORPUS["tools"].values())


def _camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(word.title() for word in rest)


_RENAMES = [
    _camel,
    str.upper,
    lambda n: n[:-1] if len(n) > 3 else n + "s",
    lambda n: n.replace("_", "-"),
    lambda n: "".join(c for i, c in enumerate(n) if i == 0 or c not in "aeiou"),
    lambda n: n.split("_")[0],
    lambda n: "x_" + n,
]


@st.composite
def drifted_calls(draw: st.DrawFn) -> tuple[str, Any]:
    tool = draw(st.sampled_from(sorted(VALID)))
    args: dict[str, Any] = copy.deepcopy(VALID[tool])
    for _ in range(draw(st.integers(1, 3))):
        keys = sorted(args)
        op = draw(
            st.sampled_from(["rename", "stringify", "case", "drop", "junk", "wrongtype", "nothing"])
        )
        if not keys:
            break
        key = draw(st.sampled_from(keys))
        if op == "rename":
            args[draw(st.sampled_from(_RENAMES))(key)] = args.pop(key)
        elif op == "stringify" and isinstance(args[key], (int, bool)):
            args[key] = json.dumps(args[key])
        elif op == "case" and isinstance(args[key], str):
            args[key] = args[key].upper()
        elif op == "drop":
            args.pop(key)
        elif op == "junk":
            args[draw(st.sampled_from(["extra", "debug", "user_email"]))] = draw(
                st.sampled_from([1, "v", True])
            )
        elif op == "wrongtype":
            args[key] = draw(st.sampled_from([[], {}, 3.5, "not-a-number"]))
    if draw(st.booleans()) and draw(st.integers(0, 9)) == 0:
        return tool, json.dumps(args)
    return tool, args


def _explained(outcome: Any, sent: dict[str, Any], schema: dict[str, Any]) -> None:
    repaired = {
        d.path for d in outcome.result.field_decisions() if d.kind is FieldDecisionKind.REPAIRED
    }

    def walk(
        forwarded: dict[str, Any], received: dict[str, Any], props: dict[str, Any], prefix: str
    ) -> None:
        for key, value in forwarded.items():
            path = f"{prefix}{key}"
            if path in repaired:
                continue
            if key not in received:
                assert value == props.get(key, {}).get("default", object()), f"{path} has no source"
            elif isinstance(value, dict) and isinstance(received[key], dict):
                walk(value, received[key], props.get(key, {}).get("properties", {}), f"{path}.")
            else:
                assert value == received[key], f"{path} changed with no record"

    walk(outcome.arguments, sent, schema.get("properties", {}), "")


@settings(max_examples=400, deadline=None)
@given(call=drifted_calls())
def test_property_mcp_invariants(call: tuple[str, Any]) -> None:
    tool, arguments = call
    auto = AUTO.process_call(tool, arguments)
    shadow = SHADOW.process_call(tool, arguments)

    # determinism
    assert AUTO.process_call(tool, arguments).to_dict() == auto.to_dict()

    # shadow isolation
    assert shadow.should_forward
    assert shadow.arguments == arguments
    assert shadow.auto_action is auto.action
    assert shadow.proposed_arguments == auto.proposed_arguments

    if not auto.should_forward:
        assert auto.arguments is None
        return

    definition = AUTO.get(tool).definition
    # validity
    assert AUTO.guard.validate(definition, auto.arguments).is_valid
    # idempotence
    again = AUTO.process_call(tool, auto.arguments)
    assert again.action is MCPAction.FORWARD and again.arguments == auto.arguments
    # provenance
    sent = json.loads(arguments) if isinstance(arguments, str) else arguments
    _explained(auto, sent, AUTO.get(tool).input_schema or {})
    # ambiguity safety
    for item in auto.result.ambiguous:
        for candidate in item.candidates:
            if candidate.op_type is FieldOpType.RENAME and candidate.source_path in sent:
                assert auto.arguments.get(candidate.source_path) == sent[candidate.source_path]
