def _date(shown: str) -> str:
    if shown == NA:
        return NA
    month, day, year = shown.replace(",", "").split()
    return f"{year}-{MONTHS[month]:02d}-{int(day):02d}"


def build() -> tuple[list[dict], dict]:
    records, log_items = [], []
    for repo, number, labels, state, opened, queries in REVIEWED:
        url = f"https://github.com/{REPOS[repo]}/issues/{number}"
        key = (repo, number)
        if key in REJECTED:
            classification, why = REJECTED[key]
            log_items.append(
                {
                    "url": url,
                    "labels": labels.split(),
                    "state": state,
                    "queries": queries.split(),
                    "kept": False,
                    "classification": classification,
                    "why": why,
                }
            )
            continue
        category, severity, capability, controlled, cls, paraphrase, impact, version = KEPT[key]
        confidence, reason = CONF[cls]
        ident = f"PFI-{len(records) + 1:04d}"
        records.append(
            {
                "id": ident,
                "source_platform": "github",
                "urls": [url],
                "report_date": _date(opened),
                "last_activity_date": NA,
                "project": REPOS[repo],
                "version": version,
                "description": paraphrase,
                "reproduction": NA,
                "category": category,
                "status": "open" if state == "open" else "unclear",
                "severity": severity,
                "developer_impact": impact,
                "capability": capability[0],
                "capability_basis": capability[1],
                "controlled_reproduction": controlled,
                "controlled_reproduction_note": "a fault the Phase 1/2 harness can inject"
                if controlled == "yes"
                else NA,
                "classification": CLASS[cls],
                "confidence": confidence,
                "confidence_reason": reason,
                "duplicate_of": None,
                "collected": COLLECTED,
                "query": queries.split()[0],
            }
        )
        log_items.append(
            {
                "url": url,
                "labels": labels.split(),
                "state": state,
                "queries": queries.split(),
                "kept": True,
                "record": ident,
                "classification": CLASS[cls],
            }
        )
    assert len(log_items) == len(REVIEWED) and len({i["url"] for i in log_items}) == len(REVIEWED)
    return records, {"items": log_items}


def main() -> None:
    records, log = build()
    (PFI / "corpus.jsonl").write_text(
        "".join(json.dumps(r, sort_keys=True) + "\n" for r in records)
    )
    (HERE / "2026-11-27-github-1.items.json").write_text(json.dumps(log, indent=1) + "\n")
    print(f"reviewed {len(REVIEWED)}, kept {len(records)}")


if __name__ == "__main__":
    main()
